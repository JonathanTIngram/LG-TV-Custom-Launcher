#!/usr/bin/env python3
"""Turn data/colornames.csv into app/colors.js for the random theme picker.

Only colors usable in a dark TV UI are kept: vivid mid-lightness ones for
accents and deep low-lightness ones for backgrounds.
"""
import colorsys
import csv
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CSV_PATH = os.path.join(ROOT, "data", "colornames.csv")
OUT_PATH = os.path.join(ROOT, "app", "colors.js")


def main():
    accents, darks = [], []
    with open(CSV_PATH, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            hex_ = row["hex"].lstrip("#").lower()
            if len(hex_) != 6:
                continue
            r, g, b = (int(hex_[i:i + 2], 16) / 255 for i in (0, 2, 4))
            _, l, s = colorsys.rgb_to_hls(r, g, b)
            entry = [row["name"], hex_]
            if s >= 0.45 and 0.45 <= l <= 0.72:
                accents.append(entry)
            elif s >= 0.15 and 0.05 <= l <= 0.15:
                darks.append(entry)

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_colors.py from data/colornames.csv"
                " (github.com/meodai/color-names, MIT). Do not edit.\n")
        f.write("var COLOR_ACCENTS = %s;\n" % json.dumps(accents, ensure_ascii=False, separators=(",", ":")))
        f.write("var COLOR_DARKS = %s;\n" % json.dumps(darks, ensure_ascii=False, separators=(",", ":")))
    print("Wrote %d accent and %d background colors to %s"
          % (len(accents), len(darks), os.path.normpath(OUT_PATH)))


if __name__ == "__main__":
    main()
